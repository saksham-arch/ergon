import assert from 'node:assert/strict'
const saved=new Map()
globalThis.localStorage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)}
const {marketplace,allJobs,saveProfile,publishJob,requestBooking,transitionBooking}=await import('../src/domain/marketplace.js')
const {jobStore,selectJobs}=await import('../src/domain/jobs.js')
assert.throws(()=>saveProfile('worker',{name:'',phone:'12'}))
saveProfile('employer',{name:'Employer One',phone:'9876543210'})
saveProfile('worker',{name:'Worker Two',phone:'9876543211'})
const draft={title:'Repair a wall',trade:'mason',pay:900,startDate:'2026-10-20',durationDays:2,hours:'09:00–17:00',address:'Test workshop, Marol',lngLat:[72.879,19.113],payday:'daily',bring:'Work gloves',fairWorkAccepted:true}
assert.throws(()=>publishJob({...draft,pay:0}))
assert.throws(()=>publishJob({...draft,lngLat:[190,19]}))
assert.throws(()=>publishJob({...draft,fairWorkAccepted:false}),/fair-work commitment/)
const job=publishJob(draft)
assert.equal(job.fairWorkCommitment.version,1)
assert.ok(Number.isFinite(job.fairWorkCommitment.acceptedAt))
assert.equal(allJobs().length,161)
jobStore.set(s=>({...s,selected:job.id,origin:job.lngLat}))
assert.equal(jobStore.getSnapshot().data.selected,job.id)
assert.ok(selectJobs(jobStore.getSnapshot().data).some(j=>j.id===job.id))
const booking=requestBooking(job.id)
assert.equal(booking.status,'requested')
assert.equal(requestBooking(job.id).id,booking.id,'double submit is idempotent')
assert.throws(()=>transitionBooking(booking.id,'accepted','worker'))
transitionBooking(booking.id,'accepted','employer')
assert.equal(marketplace.getSnapshot().data.bookings[0].status,'accepted')
transitionBooking(booking.id,'completed','employer')
assert.equal(marketplace.getSnapshot().data.bookings[0].status,'completed')
assert.throws(()=>transitionBooking(booking.id,'cancelled','worker'))
const seed=requestBooking('j1')
assert.throws(()=>transitionBooking(seed.id,'accepted','employer'),'cannot accept requests on another employer’s job')
transitionBooking(seed.id,'cancelled','worker')
assert.equal(marketplace.getSnapshot().data.profiles.worker.name,'Worker Two')
assert.equal(marketplace.getSnapshot().data.profiles.employer.name,'Employer One')
const persisted=JSON.parse(saved.get('ergon.v1.marketplace')).data
assert.equal(persisted.listings[0].id,job.id)
assert.equal(persisted.bookings[0].status,'completed')
console.log('Marketplace checks passed: posting, filters, separate profiles, duplicate submission, ownership, acceptance, completion, cancellation and persistence.')
